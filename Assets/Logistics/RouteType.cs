/// <summary>
/// Tipos de rutas de logística disponibles
/// </summary>
public enum RouteType
{
    Land,       // Rutas terrestres (carreteras, ferrocarriles)
    Water,      // Rutas marítimas (barcos)
    Pipe,       // Rutas de tuberías (petróleo, gas)
    Electric,   // Rutas eléctricas (transmisión de energía)
    Virtual,    // Rutas virtuales (comunicaciones, datos)
    Any         // Cualquier tipo de ruta
} 